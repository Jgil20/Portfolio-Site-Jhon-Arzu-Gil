    /*
    |--------------------------------------------------------------------------
    | Retrieve three published blog posts
    |--------------------------------------------------------------------------
    | SAP, analytics, reporting, and business-intelligence posts receive
    | a higher relevance score. If fewer than three matching posts exist,
    | the newest published posts fill the remaining positions.
    */
    $sql = "
        SELECT
            id,
            slug,
            title,
            date,
            category,
            tags,
            image,
            excerpt,
            (
                CASE
                    WHEN LOWER(category) = 'sap consulting' THEN 100
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(category) LIKE '%analytics%' THEN 80
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(category) LIKE '%business intelligence%' THEN 80
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(tags) LIKE '%sap%' THEN 60
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(tags) LIKE '%analytics%' THEN 50
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(title) LIKE '%sap%' THEN 50
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(title) LIKE '%analytics%' THEN 40
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(title) LIKE '%business intelligence%' THEN 40
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(title) LIKE '%reporting%' THEN 30
                    ELSE 0
                END
                +
                CASE
                    WHEN LOWER(title) LIKE '%data%' THEN 20
                    ELSE 0
                END
            ) AS relevance
        FROM blog_posts
        WHERE status = 'published'
          AND date <= CURDATE()
        ORDER BY
            relevance DESC,
            date DESC,
            id DESC
        LIMIT 3
    ";

    $statement = $pdo->query($sql);
    $relatedPosts = $statement->fetchAll(PDO::FETCH_ASSOC);
